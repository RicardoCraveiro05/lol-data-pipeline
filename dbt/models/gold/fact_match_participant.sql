select
    p.participant_key,
    p.match_id,
    p.puuid,
    p.champion_id,
    m.queue_id,
    m.patch,
    to_char((m.game_start_ts at time zone 'America/Sao_Paulo')::date, 'YYYYMMDD')::int as date_key,
    p.keystone_rune_id,
    p.primary_style_id,
    p.sub_style_id,
    p.team_id,
    p.team_position,
    p.win,
    p.kills,
    p.deaths,
    p.assists,
    round((p.kills + p.assists)::numeric / greatest(p.deaths, 1), 2) as kda,
    p.cs_total,
    round(p.cs_total::numeric / nullif(m.game_duration_sec / 60.0, 0), 2) as cs_per_min,
    p.gold_earned,
    p.damage_to_champions,
    p.vision_score,
    p.item_0,
    p.item_1,
    p.item_2,
    p.item_3,
    p.item_4,
    p.item_5,
    p.item_6
from {{ ref('stg_participant') }} as p
join {{ ref('stg_match') }} as m using (match_id)